import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.env.HOME_TEST_URL || 'http://127.0.0.1:5177';
const output = 'test-results/home';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
try {
  const context = await browser.newContext({ reducedMotion: 'reduce', serviceWorkers: 'block' });
  await context.route('https://**/*', route => route.abort());
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  for (const [width, height] of [[320, 568], [390, 844], [768, 1024], [1440, 900], [1920, 1080]]) {
    await page.setViewportSize({ width, height });
    await page.goto(base);
    await page.locator('.landing-page').waitFor();
    await page.locator('.landing-cover').evaluate(img => img.decode());
    await page.evaluate(() => document.fonts.ready);
    assert.equal(await page.locator('h1').count(), 1);
    assert.equal(await page.locator('h1').innerText(), 'UJELADEA');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.equal(await page.locator('footer').isVisible(), width >= 1280);
    assert.equal(await page.getByText('Distrito El Alto \u2022 INELA', { exact: true }).count(), 0);
    const title = await page.locator('h1').boundingBox();
    assert.ok(title.x >= 0 && title.x + title.width <= width);
    const hero = await page.locator('.landing-hero').boundingBox();
    assert.ok(hero.y + hero.height < height - (width < 1280 ? 84 : 0), `Next section remains visible at ${width}`);
    const buttons = await page.locator('.landing-actions a').evaluateAll(links => links.map(link => {
      const box = link.getBoundingClientRect(); return { left: box.left, right: box.right, top: box.top, bottom: box.bottom };
    }));
    assert.ok(buttons.every(box => box.bottom < height - (width < 1280 ? 84 : 0)), 'Actions remain above mobile navigation');
    assert.ok(buttons[0].right <= buttons[1].left || buttons[0].bottom <= buttons[1].top, 'Actions do not overlap');
    await page.screenshot({ path: `${output}/viewport-${width}.png` });
    await page.locator('.community-gallery').scrollIntoViewIfNeeded();
    await page.locator('.gallery-stage img').evaluate(img => img.decode());
    await page.locator('.landing-connect').scrollIntoViewIfNeeded();
    await page.locator('.landing-connect .social-links img').evaluateAll(imgs => Promise.all(imgs.map(img => img.decode())));
    assert.equal(await page.locator('.landing-connect .social-links a').count(), 4);
    assert.equal(await page.locator('.landing-connect a[data-network=facebook]').getAttribute('href'), 'https://www.facebook.com/share/1CTBBLE9pD/');
    await page.screenshot({ path: `${output}/full-${width}.png`, fullPage: true });
    assert.ok(await page.locator('.landing-particles').evaluate(el => {
      const data = el.getContext('2d').getImageData(0, 0, el.width, el.height).data;
      return data.some((value, index) => index % 4 === 3 && value > 0);
    }), `Canvas has visible pixels at ${width}`);
  }
  const gallery = page.locator('.community-gallery');
  await gallery.getByRole('button', { name: 'Foto siguiente', exact: true }).click();
  assert.equal(await gallery.locator('.gallery-stage img').getAttribute('src'), '/images/community/oracion-1600.webp');
  await gallery.getByRole('button', { name: 'Foto anterior', exact: true }).click();
  await gallery.getByRole('button', { name: 'Foto anterior', exact: true }).click();
  assert.equal(await gallery.locator('.gallery-stage img').getAttribute('src'), '/images/community/unidad-1600.webp');
  const thumb = gallery.getByRole('button', { name: /Ver foto 3:/ });
  await thumb.click();
  assert.equal(await thumb.getAttribute('aria-pressed'), 'true');
  await gallery.getByRole('button', { name: /Ampliar:/ }).click();
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  await dialog.locator('img').evaluate(img => img.decode());
  await page.screenshot({ path: `${output}/expanded-desktop.png` });
  await page.keyboard.press('ArrowRight');
  assert.match(await dialog.locator('img').getAttribute('src'), /unidad/);
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label')?.startsWith('Ampliar:'));
  await page.setViewportSize({ width: 390, height: 844 });
  await gallery.getByRole('button', { name: /Ver foto 3:/ }).click();
  await gallery.getByRole('button', { name: /Ampliar:/ }).click();
  await dialog.locator('img').evaluate(img => img.decode());
  await page.screenshot({ path: `${output}/expanded-mobile.png` });
  assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth));
  await dialog.getByRole('button', { name: 'Cerrar ventana' }).click();
  const stage = gallery.locator('.gallery-stage');
  await stage.dispatchEvent('pointerdown', { clientX: 260, clientY: 180, pointerType: 'touch' });
  await stage.dispatchEvent('pointerup', { clientX: 80, clientY: 185, pointerType: 'touch' });
  assert.match(await gallery.locator('.gallery-stage img').getAttribute('src'), /unidad/);
  // Runtime image failure is recoverable without breaking gallery navigation.
  await gallery.locator('.gallery-stage img').dispatchEvent('error');
  await gallery.getByRole('button', { name: 'Reintentar' }).click();
  await gallery.locator('.gallery-stage img').evaluate(img => img.decode());
  const canvas = page.locator('.landing-particles');
  await canvas.scrollIntoViewIfNeeded();
  const fingerprint = () => canvas.evaluate(el => {
    const pixels = el.getContext('2d').getImageData(0, 0, el.width, el.height).data;
    let sum = 0, drawn = 0;
    for (let i = 3; i < pixels.length; i += 4) { sum += pixels[i] * (i % 97); if (pixels[i]) drawn++; }
    return { sum, drawn };
  });
  const still = await fingerprint();
  assert.ok(still.drawn > 50, 'Particles are visible, not a blank canvas');
  await page.waitForTimeout(150);
  assert.deepEqual(await fingerprint(), still, 'Reduced motion stays still');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.waitForTimeout(250);
  assert.notEqual((await fingerprint()).sum, still.sum, 'Particle field animates');
  await page.mouse.move(200, 300);
  await page.waitForTimeout(150);
  assert.ok((await fingerprint()).drawn > 50);
  await page.setViewportSize({ width: 1440, height: 900 });
  await canvas.scrollIntoViewIfNeeded();
  const desktopFrame = await fingerprint();
  await page.mouse.move(400, 400);
  await page.waitForTimeout(250);
  assert.notEqual((await fingerprint()).sum, desktopFrame.sum, 'Desktop particles move too');
  assert.deepEqual(errors, []);
  await context.close();
  const crawler = await browser.newContext({ javaScriptEnabled: false });
  const noJS = await crawler.newPage();
  await noJS.goto(base);
  assert.equal(await noJS.locator('h1').innerText(), 'UJELADEA');
  assert.equal(await noJS.locator('.landing-cover').count(), 1);
  assert.equal(await noJS.locator('.social-links a').count(), 4);
  assert.ok((await noJS.locator('main').innerText()).includes('dependiente de UJELAB'));
  console.log('PASS: 5 viewports, responsive photos, social SVGs, mobile footer hidden, gallery buttons/keyboard/swipe/zoom/retry, focus restoration, canvas pixels and reduced motion, no-JS HTML, no runtime errors.');
} finally { await browser.close(); }
